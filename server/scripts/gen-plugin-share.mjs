import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
const root = new URL('../../', import.meta.url);
const source = new URL('shared/src/plugin-share/plugin-share.types.ts', root);
const sourceText = fs.readFileSync(source, 'utf8').replaceAll("from './plugin-share.schema'", "from '@trek/shared'");
const header = '// GENERATED by server/scripts/gen-plugin-share.mjs. Do not edit.\n';
const schemaPath = fileURLToPath(new URL('shared/src/plugin-share/plugin-share.schema.ts', root));
const program = ts.createProgram([schemaPath], {
  target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler, strict: true, skipLibCheck: true,
});
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
  getCanonicalFileName: name => name, getCurrentDirectory: () => fileURLToPath(root), getNewLine: () => '\n',
}));
const checker = program.getTypeChecker();
const schema = program.getSourceFile(schemaPath);
const declarations = [];
for (const node of schema.statements) {
  if (!node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) continue;
  if (ts.isTypeAliasDeclaration(node)) {
    const type = checker.typeToString(checker.getTypeFromTypeNode(node.type), node,
      ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias);
    if (/\bany\b|\bimport\s*\(|\bz\./.test(type)) throw new Error(`Non-standalone protocol type: ${node.name.text}`);
    declarations.push(`export type ${node.name.text} = ${type};`);
  } else if (ts.isInterfaceDeclaration(node)) declarations.push(node.getText(schema));
}
const constants = program.getSourceFile(fileURLToPath(source)).statements
  .filter(ts.isVariableStatement).map(node => node.getText()).join('\n');
const sdk = header + constants + '\n\n' + declarations.join('\n\n') + '\n';
for (const relative of ['plugin-sdk/src/generated/public-share.ts', 'server/src/nest/plugins/protocol/public-share.ts']) {
  const expected = relative.startsWith('plugin-sdk/') ? sdk : header + sourceText;
  const target = new URL(relative, root);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== expected) {
      throw new Error('Public share protocol drift: run node server/scripts/gen-plugin-share.mjs');
    }
  } else {
    fs.mkdirSync(fileURLToPath(new URL('.', target)), { recursive: true });
    fs.writeFileSync(target, expected);
  }
}
